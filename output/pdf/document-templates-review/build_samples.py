def table(headers, rows, widths):
    data = [[p(x, 'SmallNoto') for x in headers]] + [[p(x, 'SmallNoto') for x in row] for row in rows]
    t = Table(data, colWidths=widths, repeatRows=1, hAlign='LEFT')
