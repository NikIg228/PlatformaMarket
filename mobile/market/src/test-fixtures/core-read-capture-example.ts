import { createMobileReadQueries, type MobileReadQuery } from "../../../../contracts/mobile-read/read-queries";
import { orderWorkflowResponseSchema } from "../../../../packages/schemas/src/order-workflow";
import { bindMarketReads } from "../market-transport";
import { listDraftScope, listDraftPayload, listDraftComparison } from "./list-draft";
import { commandCart } from "./cart-commands";
import { intentCheckout } from "./payment-intent";
import { ownOrganization } from "./organization";
import { supportSummary, supportDetail } from "./support";

/** Synthetic only. Route text is generated by the same native binding/dispatcher, not a second route table. */
export async function coreReadCaptureExample(kind: MobileReadQuery["kind"] = "workflow") {
  const scope = Object.freeze({ ...listDraftScope, environment: "https://market.example.invalid/api" });
  let query: MobileReadQuery, body: unknown;
  switch (kind) {
    case "catalog": query = { kind, input: { q: "SYNTHETIC", offset: 0, limit: 24 } }; body = listDraftPayload("catalog-null-price"); break;
    case "comparison": { const value = listDraftComparison(); query = { kind, input: { productId: value.product.id, variantId: value.offers[0]!.variantId, quantity: "1.000000" } }; body = value; break; }
    case "workspace-orders": query = { kind, input: { limit: 50, q: "" } }; body = listDraftPayload("workspace-orders-page"); break;
    case "organization-profile": query = { kind }; body = ownOrganization({ organizationId: scope.organizationId }); break;
    case "workflow": { const value = orderWorkflowResponseSchema.parse(listDraftPayload("order-workflow-minimal")); query = { kind, orderId: value.orderId }; body = value; break; }
    case "cart": { const value = commandCart(); query = { kind, cartId: value.id }; body = value; break; }
    case "checkout": { const value = intentCheckout(); query = { kind, checkoutId: value.id, cartId: value.cartId }; body = value; break; }
    case "workspace-carts": query = { kind, input: { limit: 1, q: "" } }; body = { current: commandCart(), items: [], nextCursor: null }; break;
    case "support-tickets": query = { kind, input: { offset: 0, q: "SYNTHETIC", sort: "recent" } }; body = [supportSummary({ organizationId: scope.organizationId })]; break;
    case "support-ticket": { const value = supportDetail({ organizationId: scope.organizationId }); query = { kind, ticketId: value.id }; body = value; break; }
    default: throw Error("Unsupported synthetic core read kind");
  }
  const records: { method: "GET"; path: string; httpStatus: number; body: unknown }[] = [];
  const client = bindMarketReads(async path => { records.push({ method: "GET", path, httpStatus: 200, body }); return body; }, scope.organizationId), queries = createMobileReadQueries(scope, client);
  await queries.load(query); queries.reset(scope, client);
  return { formatVersion: 1 as const, scope, query, records };
}
