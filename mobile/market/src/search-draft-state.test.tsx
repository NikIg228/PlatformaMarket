import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { act, fireEvent, render, screen } from "@testing-library/react-native";
import { jest } from "@jest/globals";
import App from "../App";
import { offerComparisonResponseSchema } from "../../../packages/schemas/src/core-api";
import type { MobileReadClient, ReadScope } from "./read-controller";
import { copy } from "./i18n";
const corpus = JSON.parse(readFileSync(resolve(__dirname, "../../../contracts/mobile-read/fixtures.json"), "utf8")) as { cases: { id: string; payload: unknown }[] };
const fixture = (id: string): unknown => JSON.parse(JSON.stringify(corpus.cases.find(item => item.id === id)!.payload));
const scope: ReadScope = { product: "market", environment: "synthetic-offline", userId: "00000000-0000-4000-8000-000000000020", organizationId: "00000000-0000-4000-8000-000000000004", generation: 1 };
function client() { return { searchCatalog: jest.fn<MobileReadClient["searchCatalog"]>().mockResolvedValue(fixture("catalog-null-price")), compareOffers: jest.fn<MobileReadClient["compareOffers"]>().mockResolvedValue(fixture("comparison-exact-offer")), workspaceOrders: jest.fn<MobileReadClient["workspaceOrders"]>().mockResolvedValue(fixture("workspace-orders-page")), getOrderWorkflow: jest.fn<MobileReadClient["getOrderWorkflow"]>().mockResolvedValue(fixture("order-workflow-minimal")) }; }
it.each(["ru", "kk"] as const)("identifies applied catalog and order searches separately from unsent/cleared drafts in %s", async locale => {
  const api = client(), t = copy[locale];
  await render(<App session={{ scope, client: api, organizationName: "SYNTHETIC organization" }} locale={locale} />);
  await screen.findByText("SYNTHETIC product");
  await fireEvent.changeText(screen.getByLabelText(t.search), " catalog exact ");
  expect(screen.getByText(t.searchDraft)).toBeOnTheScreen(); expect(api.searchCatalog).toHaveBeenCalledTimes(1);
  await fireEvent(screen.getByLabelText(t.search), "submitEditing");
  await screen.findByText("SYNTHETIC product");
  expect(screen.getByText(`${t.searchApplied}: catalog exact`)).toBeOnTheScreen();
  expect(screen.queryByText(t.searchDraft)).toBeNull();
  await fireEvent.changeText(screen.getByLabelText(t.search), "");
  expect(screen.getByText(t.searchDraft)).toBeOnTheScreen();
  expect(screen.getByText(`${t.searchApplied}: catalog exact`)).toBeOnTheScreen();
  expect(api.searchCatalog).toHaveBeenCalledTimes(2);
  await fireEvent.press(screen.getByRole("tab", { name: t.orders }));
  await screen.findByText("SYNTHETIC-READ-001");
  await fireEvent.changeText(screen.getByLabelText(t.searchOrders), "order exact");
  await fireEvent(screen.getByLabelText(t.searchOrders), "submitEditing");
  await screen.findByText("SYNTHETIC-READ-001");
  expect(screen.getByText(`${t.searchApplied}: order exact`)).toBeOnTheScreen();
  expect(screen.queryByText(`${t.searchApplied}: catalog exact`)).toBeNull();
  await fireEvent.press(screen.getByRole("tab", { name: t.catalog }));
  await screen.findByText("SYNTHETIC product");
  expect(screen.getByText(`${t.searchApplied}: catalog exact`)).toBeOnTheScreen();
  expect(screen.getByText(t.searchDraft)).toBeOnTheScreen();
  await fireEvent.press(screen.getByRole("button", { name: t.clear }));
  await screen.findByText("SYNTHETIC product");
  expect(screen.queryByText(`${t.searchApplied}: catalog exact`)).toBeNull();
  expect(screen.queryByText(t.searchDraft)).toBeNull();
});
it("uses current locale for applied/draft copy through a failed pending read without applying the new draft", async () => {
  const api = client(); const session = { scope, client: api, organizationName: "SYNTHETIC organization" };
  const rendered = await render(<App session={session} />); await screen.findByText("SYNTHETIC product");
  let reject!: (reason: Error) => void;
  api.searchCatalog.mockReturnValueOnce(new Promise((_resolve, no) => { reject = no; }));
  await fireEvent.changeText(screen.getByLabelText(copy.ru.search), "applied");
  await fireEvent(screen.getByLabelText(copy.ru.search), "submitEditing");
  await fireEvent.changeText(screen.getByLabelText(copy.ru.search), "unsent");
  await rendered.rerender(<App session={session} locale="kk" />);
  expect(screen.getByText(`${copy.kk.searchApplied}: applied`)).toBeOnTheScreen();
  expect(screen.getByText(copy.kk.searchDraft)).toBeOnTheScreen();
  await act(async () => reject(new Error("SYNTHETIC offline")));
  await screen.findByRole("alert", { name: `${copy.kk.error}. ${copy.kk.errorBody}` });
  expect(screen.getByText(`${copy.kk.searchApplied}: applied`)).toBeOnTheScreen();
  expect(api.searchCatalog.mock.calls.at(-1)?.[0]).toMatchObject({ q: "applied" });
  expect(screen.getByLabelText(copy.kk.search)).toHaveProp("value", "unsent");
});
