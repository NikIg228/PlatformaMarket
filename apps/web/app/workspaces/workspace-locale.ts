export type WorkspaceLocale = "ru" | "kk";

export function workspaceLocale(value: string | null): WorkspaceLocale {
  return value === "kk" ? "kk" : "ru";
}

export function withWorkspaceLocale(href: string, locale: WorkspaceLocale) {
  if (!href.startsWith("/") || href.startsWith("//")) return href;
  const url = new URL(href, "https://workspace.invalid");
  if (locale === "kk") url.searchParams.set("lang", "kk");
  else url.searchParams.delete("lang");
  return url.pathname + url.search + url.hash;
}

