export type ResponseStateOrder = {
  status?: string;
  responseDeadlineAt?: string | null;
  responseReceivedAt?: string | null;
  responseRemindedAt?: string | null;
  responseOverdueAt?: string | null;
  responseEscalatedAt?: string | null;
};

export function orderResponseState(order: ResponseStateOrder) {
  if (!order.responseDeadlineAt) return "legacy";
  if (order.status === "CANCELLED") return "stopped";
  if (order.responseReceivedAt) return Date.parse(order.responseReceivedAt) > Date.parse(order.responseDeadlineAt) ? "answeredLate" : "answered";
  if (order.status && order.status !== "AWAITING_CONFIRMATION") return "answered";
  if (order.responseEscalatedAt) return "escalated";
  if (order.responseOverdueAt) return "overdue";
  if (order.responseRemindedAt) return "reminded";
  return "waiting";
}

